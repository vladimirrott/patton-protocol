"""P1L's pre-registration, generated from the code so the two cannot drift.

    python3 -m patton_lab.p1l.prereg            # write lab/prereg/2026-11-04-p1l-preregistration.md
    python3 -m patton_lab.p1l.prereg --check    # fail when the file no longer matches the code

`python3 -m patton_lab.fleet.runner study --set p1l` refuses to start unless `--check` passes.
"""

