        "arm: subagents (`[agents] enabled = false`), goals, web search, apps, plugins, image generation, browser "
        "and computer use, memories, request compression.",
        f"- Fixtures: {', '.join(FIXTURES)} (the 16 test fixtures of the Claude Code study).",
        f"- Reps: r = {REPS}, chosen by the person from the calibration. Planned runs: "
        f"{sum(planned_runs().values())}.",
