        "refuses to start when this file is stale, when the trace marker is missing or from another tree, or when "
        "either Codex binary differs from its pinned hash. Every record stores its seed. The analysis uses the "
        "leading complete reps: rep 0, 1, ... up to the first rep with a missing run (a rep is complete when all 80 "
        "of its runs are stored).",
        f"- Quota: before each run the study reads the latest stored run that carries readings. No run starts while "
